def write_detparams(
    path: str,
    ring_filename: str,
    scanner: stir.Scanner,
    phys: PhysicalSpec,
    num_axial_rings: int,
    phys_axial: int,
    do_forced_interaction: bool = False,
) -> None:
    pitch = axial_block_pitch_cm(phys, phys_axial)
    z_start = -(num_axial_rings * pitch) / 2.0 + pitch / 2.0
    ring_basename = os.path.basename(ring_filename)

    with open(path, "w") as f:
        f.write(_file_header("Block Detector Parameter File", scanner.get_name()))

        f.write("ENUM\tdetector_type = block\n\n")
        fi_str = "true" if do_forced_interaction else "false"
        f.write(f"BOOL\tdo_forced_interaction = {fi_str}\n\n")
        f.write(f"REAL\treference_energy_keV\t\t= {scanner.get_reference_energy():.1f}\n")
        energy_res = scanner.get_energy_resolution()
        if energy_res <= 0:
            # BGO default; warn the user
            import warnings
            warnings.warn(
                f"{scanner.get_name()}: STIR energy_resolution is 0 (unknown). "
                "Defaulting to 0.20 (20%) for BGO. Override PhysicalSpec if needed."
            )
            energy_res = 0.20
        f.write(f"REAL\tenergy_resolution_percentage\t= {energy_res * 100:.1f}\n\n")
        f.write("ENUM\tblocktomo_position_algorithm = snap_centroid_to_crystal_center\n\n")
        f.write(f"NUM_ELEMENTS_IN_LIST\tblocktomo_num_rings = {num_axial_rings}\n\n")

        for i in range(num_axial_rings):
            z_shift = z_start + i * pitch
            f.write(f"# Ring {i}  (axial shift {z_shift:.4f} cm)\n")
            f.write(f"NUM_ELEMENTS_IN_LIST\tblocktomo_ring_description_list = 3\n")
            f.write(f"\tSTR\tblocktomo_ring_parameter_file\t\t= \"{ring_basename}\"\n")
            f.write(f"\tREAL\tblocktomo_ring_axial_shift\t\t= {z_shift:.8f}\n")
            f.write(f"\tREAL\tblocktomo_ring_transaxial_rotation\t= 0.0\n\n")

    print(f"  Wrote {path}")
